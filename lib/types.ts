/**
 * @file types.ts
 * @description Core TypeScript types for the Saans Civic Air Quality Briefing Studio.
 * Defines models for raw ingestion, data hygiene flags, statistics, traceable findings,
 * verified actions, and multi-tier civic advisories.
 */

/**
 * Standard audience roles who can request and act on civic air quality briefs.
 */
export type TargetRole = "ward_officer" | "housing_society" | "school" | "all";

/**
 * Air quality severity or priority classifications.
 */
export type SeverityLevel = "low" | "moderate" | "high" | "critical";

/**
 * Action priority classifications.
 */
export type ActionPriority = "immediate" | "high" | "medium" | "low";

/**
 * Reading comprehension levels for citizen advisories.
 */
export type ReadingLevel = "simple" | "standard" | "expert";

/**
 * Specific demographic or vulnerable groups targeted by citizen advisories.
 */
export type AdvisoryAudience = "general" | "children" | "older_adults" | "sensitive_groups";

/**
 * Verification state for AI-cited findings and actions.
 */
export type VerificationStatus = "verified" | "unverified";

/**
 * National Air Quality Index (NAQI) categories as defined by India's CPCB.
 */
export type NAQICategory =
  | "Good"
  | "Satisfactory"
  | "Moderate"
  | "Poor"
  | "Very Poor"
  | "Severe"
  | "N/A";

/**
 * Trend trajectory calculated across temporal halves of the dataset.
 */
export type TrendDirection = "rising" | "falling" | "steady" | "insufficient_data";

/**
 * Types of data quality defects detected by deterministic rules.
 */
export type QualityFlagType =
  | "missing"
  | "negative"
  | "unit_mismatch"
  | "spike"
  | "stuck_sensor";

/**
 * Normalized representation of a single ingested data row.
 */
export interface Row {
  /** 1-based sequential row identifier (1..n) for audit traceability. */
  rowNumber: number;
  /** Normalized name of the monitoring ward, station, or geographic location. */
  location: string;
  /** Normalized timestamp string if detected, otherwise undefined. */
  timestamp?: string;
  /** Original unparsed cell values mapped by header column. */
  rawValues: Record<string, string>;
  /** Cleaned pollutant values in standard µg/m³, or null if missing/invalid. */
  pollutants: Record<string, number | null>;
  /** Optional notes regarding column unit detection or conversions. */
  unitNotes?: Record<string, string>;
}

/**
 * A single pollutant measurement extracted from a data row.
 */
export interface Reading {
  /** 1-based row number originating the reading. */
  rowNumber: number;
  /** Location or ward identifier. */
  location: string;
  /** Timestamp of the observation if available. */
  timestamp?: string;
  /** Canonical pollutant identifier (e.g. "pm25", "pm10", "no2"). */
  pollutant: string;
  /** Raw text string from the original cell. */
  rawVal: string;
  /** Normalized numeric value in standard µg/m³, or null if missing/invalid. */
  value: number | null;
  /** Unit of measurement (e.g. "ug/m3", "mg/m3"). */
  unit: string;
}

/**
 * A data hygiene or sensor fault flag identified in a specific row.
 */
export interface QualityFlag {
  /** 1-based row number where the defect was detected. */
  rowNumber: number;
  /** Location or ward identifier. */
  location: string;
  /** Specific pollutant affected, if applicable. */
  pollutant?: string;
  /** Header column name where the defect was detected. */
  column?: string;
  /** Category of quality flag. */
  type: QualityFlagType;
  /** Human-readable explanation of why this flag was raised. */
  message: string;
  /** Value that triggered the flag, if applicable. */
  value?: number | string | null;
}

/**
 * Aggregated statistics for a specific location and pollutant.
 */
export interface LocationStats {
  /** Location or ward identifier. */
  location: string;
  /** Canonical pollutant identifier (e.g. "pm25", "pm10"). */
  pollutant: string;
  /** Total count of non-missing, valid readings. */
  count: number;
  /** Total count of missing or non-numeric values (computed by code, never AI). */
  missing: number;
  /** Arithmetic mean of valid readings, or null if no valid data. */
  mean: number | null;
  /** Maximum valid reading recorded, or null if no valid data. */
  max: number | null;
  /** Median of valid readings, or null if no valid data. */
  median?: number | null;
  /** Mean of the first chronological half of valid readings. */
  firstHalfMean: number | null;
  /** Mean of the second chronological half of valid readings. */
  secondHalfMean: number | null;
  /** Directional trend comparing second half to first half. */
  trend: TrendDirection;
  /** India NAQI category based on official CPCB 24h breakpoints. */
  naqiCategory: NAQICategory;
}

/**
 * Traceable insight or observation generated by AI and verified by code.
 */
export interface Finding {
  /** Unique finding identifier. */
  id: string;
  /** Primary location or ward referenced. */
  location: string;
  /** Pollutant associated with the finding, if applicable. */
  pollutant?: string;
  /** Short headline summarizing the insight. */
  headline: string;
  /** Detailed plain-language description of the trend or anomaly. */
  description: string;
  /** Row numbers (1..n) cited as evidence from the raw dataset. */
  citedRowNumbers: number[];
  /** Code-verified status: verified if all rows exist and match the location. */
  verificationStatus?: VerificationStatus;
  /** Explanation if the finding failed deterministic verification. */
  verificationReason?: string;
  /** Severity rating for civic prioritization. */
  severity?: SeverityLevel;
}

/**
 * Actionable recommendation tailored to a specific audience role.
 */
export interface Action {
  /** Unique action identifier. */
  id: string;
  /** Priority classification for implementation. */
  priority: ActionPriority;
  /** Role responsible for executing this action. */
  targetRole: TargetRole;
  /** Specific location or ward for the action, or "all" for regional actions. */
  location?: string;
  /** Concise action headline. */
  title: string;
  /** Concrete operational step or countermeasure. */
  action: string;
  /** Data-grounded justification explaining why this action is required. */
  rationale: string;
  /** Row numbers (1..n) cited as evidence from the raw dataset. */
  citedRowNumbers: number[];
  /** Code-verified status. */
  verificationStatus?: VerificationStatus;
  /** Explanation if the action citations failed verification. */
  verificationReason?: string;
}

/**
 * Public-facing civic advisory tailored by language, reading level, and vulnerability.
 */
export interface Advisory {
  /** Language code (e.g. "en", "hi", "mr", "ta"). */
  language: string;
  /** Reading level suited for the target demographic. */
  readingLevel: ReadingLevel;
  /** Target vulnerable audience group. */
  targetAudience: AdvisoryAudience;
  /** Clear advisory headline. */
  title: string;
  /** Plain-language health guidance and situational awareness. */
  content: string;
  /** Actionable list of protective measures citizens should take. */
  dos: string[];
  /** High-risk activities citizens should avoid. */
  donts: string[];
}

/**
 * Complete civic air quality brief combining deterministic stats, verified findings,
 * operational notes, and public advisories.
 */
export interface Brief {
  /** Unique brief identifier. */
  id: string;
  /** ISO timestamp when the brief was generated. */
  createdAt: string;
  /** Audience role the briefing was generated for. */
  audienceRole: "ward_officer" | "housing_society" | "school";
  /** Title of the briefing document. */
  title: string;
  /** Executive summary of current air quality and urgent concerns. */
  summary: string;
  /** List of locations identified as high-risk or severe hotspots. */
  hotspots: string[];
  /** Deterministic summary of data quality and sensor hygiene. */
  dataQualitySummary: {
    totalRows: number;
    validRows: number;
    missingCount: number;
    flagCount: number;
    reliabilityAssessment: string;
    flagsByType: Record<string, number>;
  };
  /** Code-verified key findings. */
  findings: Finding[];
  /** Prioritized, role-targeted recommendations. */
  actions: Action[];
  /** Administrative briefing note for official records and field staff. */
  internalBriefingNote: {
    title: string;
    executiveSummary: string;
    wardBreakdown: string;
    operationsChecklist: string[];
  };
  /** Multi-lingual, accessible citizen advisories. */
  citizenAdvisories: Advisory[];
  /** Comparative delta relative to a previous briefing note, if provided. */
  previousBriefComparison?: {
    previousBriefId?: string;
    trendSummary: string;
    changes: string[];
  } | null;
}


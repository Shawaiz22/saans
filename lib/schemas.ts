/**
 * @file schemas.ts
 * @description Zod validation schemas for API requests, Gemini response structured output,
 * and data structures within the Saans Civic Air Quality Briefing Studio.
 */

import { z } from "zod";
import { MAX_BODY_BYTES } from "./limits";

/**
 * Zod schema for briefing generation API request payload.
 */
export const BriefingRequestSchema = z.object({
  /** Raw CSV, TSV, or tabular text representing air quality observations. */
  csvText: z
    .string()
    .min(1, "Air quality data text cannot be empty.")
    .max(MAX_BODY_BYTES, `Data size exceeds maximum allowed limit of ${MAX_BODY_BYTES} bytes.`),

  /** Intended civic stakeholder role for targeted guidance. */
  audienceRole: z.enum(["ward_officer", "housing_society", "school"]).default("ward_officer"),

  /** Target languages for citizen advisories (e.g. ["en", "hi", "mr"]). */
  targetLanguages: z.array(z.string()).default(["en", "hi"]),

  /** Target reading levels for citizen advisories. */
  readingLevels: z
    .array(z.enum(["simple", "standard", "expert"]))
    .default(["simple", "standard"]),

  /** Optional previous brief payload to compare trends against. */
  previousBrief: z
    .object({
      id: z.string().optional(),
      summary: z.string().optional(),
      hotspots: z.array(z.string()).optional(),
      createdAt: z.string().optional(),
    })
    .nullable()
    .optional(),
});

export type BriefingRequest = z.infer<typeof BriefingRequestSchema>;

/**
 * Zod schema for individual findings produced by Gemini.
 */
export const FindingSchema = z.object({
  id: z.string().optional(),
  location: z.string().min(1, "Location is required for finding."),
  pollutant: z.string().optional(),
  headline: z.string().min(1, "Headline is required."),
  description: z.string().min(1, "Description is required."),
  citedRowNumbers: z.array(z.number()),
  severity: z.enum(["low", "moderate", "high", "critical"]).default("moderate"),
});

/**
 * Zod schema for role-targeted operational actions produced by Gemini.
 */
export const ActionSchema = z.object({
  id: z.string().optional(),
  priority: z.enum(["immediate", "high", "medium", "low"]).default("high"),
  targetRole: z.enum(["ward_officer", "housing_society", "school", "all"]).default("all"),
  location: z.string().optional(),
  title: z.string().min(1, "Action title is required."),
  action: z.string().min(1, "Action description is required."),
  rationale: z.string().min(1, "Action rationale is required."),
  citedRowNumbers: z.array(z.number()),
});

/**
 * Zod schema for public citizen advisory notes.
 */
export const CitizenAdvisorySchema = z.object({
  language: z.string().default("en"),
  readingLevel: z.enum(["simple", "standard", "expert"]).default("simple"),
  targetAudience: z
    .enum(["general", "children", "older_adults", "sensitive_groups"])
    .default("general"),
  title: z.string().min(1, "Advisory title is required."),
  content: z.string().min(1, "Advisory content is required."),
  dos: z.array(z.string()).min(1, "At least one protective measure (DO) is required."),
  donts: z.array(z.string()).min(1, "At least one high-risk warning (DON'T) is required."),
});

/**
 * Zod schema for the internal briefing note for administrative records.
 */
export const InternalBriefingNoteSchema = z.object({
  title: z.string().default("Ward Air Quality Internal Briefing Note"),
  executiveSummary: z.string().min(1, "Executive summary is required."),
  wardBreakdown: z.string().min(1, "Ward breakdown is required."),
  operationsChecklist: z.array(z.string()).min(1, "Operations checklist cannot be empty."),
});

/**
 * Zod schema for comparison with previous brief.
 */
export const PreviousBriefComparisonSchema = z
  .object({
    trendSummary: z.string(),
    changes: z.array(z.string()),
  })
  .nullable()
  .optional();

/**
 * Complete Zod schema for validating the structured JSON generated by Gemini.
 */
export const GeminiResponseSchema = z.object({
  title: z.string().default("Civic Air Quality Briefing"),
  summary: z.string().min(1, "Summary is required."),
  hotspots: z.array(z.string()),
  findings: z.array(FindingSchema),
  actions: z.array(ActionSchema),
  internalBriefingNote: InternalBriefingNoteSchema,
  citizenAdvisories: z.array(CitizenAdvisorySchema),
  previousBriefComparison: PreviousBriefComparisonSchema,
});

export type GeminiResponse = z.infer<typeof GeminiResponseSchema>;


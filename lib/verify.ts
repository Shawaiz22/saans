/**
 * @file verify.ts
 * @description Pure verification engine for grounding and traceability of GenAI findings and actions.
 * Given AI-generated findings or actions with cited row numbers and parsed rows,
 * marks each item "verified" if and only if all cited row numbers exist AND belong to the location it names;
 * otherwise marks "unverified" with a precise audit reason (e.g. row non-existence or location mismatch).
 */

import { Row, Finding, Action, VerificationStatus } from "./types";

/**
 * Normalizes location string for robust case-insensitive comparison.
 *
 * @param loc - Raw location name.
 * @returns Cleaned lower-case string.
 */
export function normalizeLocation(loc: string): string {
  return loc.trim().toLowerCase().replace(/[\s\-_]+/g, " ");
}

/**
 * Checks whether a row's location matches an item's specified location.
 * Allows exact normalized match or clear substring containment (e.g. "Ward 12" matches "Ward 12 (Indiranagar)").
 *
 * @param rowLocation - Location attached to the parsed data row.
 * @param itemLocation - Location claimed by the AI finding or action.
 * @returns True if the locations are compatible.
 */
export function isLocationMatch(rowLocation: string, itemLocation: string): boolean {
  const r = normalizeLocation(rowLocation);
  const i = normalizeLocation(itemLocation);

  if (r === i) return true;
  if (r.includes(i) || i.includes(r)) return true;

  // Extract digits (e.g. Ward 12 vs Ward-12)
  const rDigits = r.match(/\d+/g)?.join("");
  const iDigits = i.match(/\d+/g)?.join("");
  if (rDigits && iDigits && rDigits === iDigits) {
    return true;
  }

  return false;
}

/**
 * Verifies a single item (Finding or Action) against the dataset rows.
 *
 * @param item - Finding or Action with citedRowNumbers and optional location.
 * @param rowMap - Map of rowNumber -> Row for fast lookup.
 * @param totalRows - Total number of rows in the parsed dataset.
 * @returns Verification result with status and explanatory reason.
 */
export function verifyItemTraceability(
  item: { citedRowNumbers?: number[]; location?: string },
  rowMap: Map<number, Row>,
  totalRows: number
): { status: VerificationStatus; reason?: string } {
  const citedRows = item.citedRowNumbers ?? [];

  if (citedRows.length === 0) {
    return {
      status: "unverified",
      reason: "No data rows cited to substantiate this claim.",
    };
  }

  const failures: string[] = [];

  for (const rowNum of citedRows) {
    const row = rowMap.get(rowNum);

    if (!row) {
      failures.push(
        `Row ${rowNum} does not exist in dataset (valid range: 1..${totalRows}).`
      );
      continue;
    }

    if (item.location && item.location.trim().toLowerCase() !== "all") {
      if (!isLocationMatch(row.location, item.location)) {
        failures.push(
          `Row ${rowNum} belongs to '${row.location}', not '${item.location}'.`
        );
      }
    }
  }

  if (failures.length > 0) {
    return {
      status: "unverified",
      reason: failures.join(" "),
    };
  }

  return {
    status: "verified",
  };
}

/**
 * Deterministically verifies all AI-generated findings against parsed dataset rows.
 *
 * @param findings - Array of Findings generated by AI.
 * @param rows - Normalized dataset rows.
 * @returns New array of Findings with verificationStatus and verificationReason populated.
 */
export function verifyFindings(findings: Finding[], rows: Row[]): Finding[] {
  const rowMap = new Map<number, Row>();
  for (const r of rows) {
    rowMap.set(r.rowNumber, r);
  }

  return findings.map((f) => {
    const result = verifyItemTraceability(
      { citedRowNumbers: f.citedRowNumbers, location: f.location },
      rowMap,
      rows.length
    );

    return {
      ...f,
      verificationStatus: result.status,
      verificationReason: result.reason,
    };
  });
}

/**
 * Deterministically verifies all AI-generated actions against parsed dataset rows.
 *
 * @param actions - Array of Actions generated by AI.
 * @param rows - Normalized dataset rows.
 * @returns New array of Actions with verificationStatus and verificationReason populated.
 */
export function verifyActions(actions: Action[], rows: Row[]): Action[] {
  const rowMap = new Map<number, Row>();
  for (const r of rows) {
    rowMap.set(r.rowNumber, r);
  }

  return actions.map((a) => {
    const result = verifyItemTraceability(
      { citedRowNumbers: a.citedRowNumbers, location: a.location },
      rowMap,
      rows.length
    );

    return {
      ...a,
      verificationStatus: result.status,
      verificationReason: result.reason,
    };
  });
}

/**
 * Direct functional verifier checking if all cited row numbers exist AND belong to the named location.
 *
 * @param location - Target location name.
 * @param citedRowNumbers - Row identifiers (1..n).
 * @param rows - Normalized dataset rows.
 * @returns Verification status and descriptive reason if unverified.
 */
export function verifyCitations(
  location: string,
  citedRowNumbers: number[],
  rows: Row[]
): { status: "verified" | "unverified"; reason?: string } {
  const rowMap = new Map<number, Row>();
  for (const r of rows) {
    rowMap.set(r.rowNumber, r);
  }
  return verifyItemTraceability({ location, citedRowNumbers }, rowMap, rows.length);
}

